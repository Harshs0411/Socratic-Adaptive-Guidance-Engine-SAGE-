from typing import List, Literal, Optional

from pydantic import BaseModel, Field


QuestionType = Literal[
    "conceptual",
    "objective",
    "application",
]


EvaluatorType = Literal[
    "llm",
    "numeric",
    "sequence",
    "set",
    "symbolic",
    "exact",
]


class ProblemContext(BaseModel):
    """
    Explicit context for an objective/application problem.

    This prevents SAGE from having to reconstruct or
    hallucinate numerical examples across tutoring turns.
    """

    description: Optional[str] = Field(
        default=None,
        description=(
            "The complete problem context required to "
            "answer the current question. Include given "
            "signals, equations, values, assumptions, or "
            "other information that the student needs."
        ),
    )

    variables: dict[str, str] = Field(
        default_factory=dict,
        description=(
            "Important variables or given values used "
            "by the current problem. For example: "
            "x='[1,2]', h='[3,4]', n='1'."
        ),
    )


class SocraticResponse(BaseModel):
    """
    Structured response generated by SAGE.

    SAGE must generate one coherent assessment unit:

        question
            ↓
        expected_answer
            ↓
        evaluator_type
            ↓
        evaluation_criteria

    These fields must all refer to the SAME question.
    """

    message: str = Field(
        description=(
            "The complete student-facing response. "
            "It may contain a short explanation, hint, "
            "or context followed by exactly one question."
        )
    )

    question: str = Field(
        description=(
            "Exactly ONE question that the student should "
            "answer. The expected_answer MUST directly "
            "answer this exact question and must not "
            "contain answers to additional unasked questions."
        )
    )

    action: Literal[
        "initial",
        "probe",
        "hint",
        "scaffold",
        "explain",
    ] = Field(
        description=(
            "The teaching action used for this turn."
        )
    )

    question_type: QuestionType = Field(
        description=(
            "The pedagogical type of the question."
        )
    )

    evaluator_type: EvaluatorType = Field(
        description=(
            "How the student's answer should be evaluated. "
            "\n\n"
            "llm: conceptual, explanatory, application, "
            "or semantically complex mathematical reasoning."
            "\n\n"
            "numeric: exactly one numerical result."
            "\n\n"
            "sequence: an ordered numerical sequence, "
            "vector, or list."
            "\n\n"
            "set: an unordered collection of values."
            "\n\n"
            "symbolic: symbolic mathematical expressions "
            "where semantic mathematical equivalence matters."
            "\n\n"
            "exact: short exact terms or definitions where "
            "deterministic matching is appropriate."
            "\n\n"
            "The evaluator_type MUST match the answer format "
            "required by the question."
        )
    )

    expected_answer: str = Field(
        description=(
            "The correct answer to the EXACT question. "
            "Do not include answers to additional questions. "
            "Do not provide a larger solution when the "
            "question asks for only one component."
        )
    )

    evaluation_criteria: List[str] = Field(
        default_factory=list,
        description=(
            "Specific criteria used to determine whether "
            "the student correctly answered THIS question. "
            "These criteria must correspond directly to "
            "the question and expected answer."
        )
    )

    problem_context: Optional[ProblemContext] = Field(
        default=None,
        description=(
            "Explicit context required for the current "
            "problem. Use this for numerical examples, "
            "signals, equations, values, or assumptions "
            "that must remain consistent across turns."
        ),
    )